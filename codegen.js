/* Generate reproducible Python geometry from the FINAL vector loops (no browser dependencies). */
(function (root) {
'use strict';
function generatedPython(geometry, options = {}) {
  if (!geometry || !Array.isArray(geometry.loops) || !geometry.loops.length) throw Error('请先生成有效的图案轮廓。');
  if (geometry.loops.some(l => l.open)) throw Error('存在未闭合的轮廓；请连接端点后再生成代码。');
  const kind = options.kind || 'pypssfss', grid = Number(options.grid ?? 128);
  if (!['pypssfss', 'dxf'].includes(kind)) throw Error('不支持的代码格式。');
  if (!Number.isInteger(grid) || ![32,64,128,256,512].includes(grid)) throw Error('网格分辨率无效。');
  const width = Number(geometry.width), height = Number(geometry.height);
  if (![width,height,geometry.ox,geometry.oy].every(Number.isFinite) || width <= 0 || height <= 0) throw Error('实际宽高或原点无效。');
  const loops = geometry.loops.map(l => {
    if (!Array.isArray(l.points) || l.points.length < 3 || l.points.some(p => !Array.isArray(p) || p.length !== 2 || !p.every(Number.isFinite))) throw Error('轮廓点坐标异常。');
    return {hole:!!l.hole,points:l.points.map(p => p.map(n => Number(n.toFixed(9))))};
  });
  const payload = JSON.stringify({width_mm:width,height_mm:height,left_mm:-geometry.ox,bottom_mm:-geometry.oy,loops},null,2);
  const shared = [
    '# Generated by FSS Pattern Lab; geometry is in millimetres (XY plane).',
    '# Coordinates are the same FINAL edited/scaled vertices used for the DXF export.',
    '# Outer contours, holes, and nested metal islands are represented by even-odd filling.',
    '# This is a geometry export, NOT an inverse design or validated EM result.',
    'import json',
    "GEOMETRY = json.loads(r'''",
    payload,
    "''')",
    "WIDTH_MM = GEOMETRY['width_mm']",
    "HEIGHT_MM = GEOMETRY['height_mm']",
    "LEFT_MM = GEOMETRY['left_mm']",
    "BOTTOM_MM = GEOMETRY['bottom_mm']",
    "LOOPS_MM = GEOMETRY['loops']",
    ''
  ].join('\n');
  if (kind === 'dxf') {
    return shared + [
      '# pip install ezdxf',
      'import ezdxf',
      '',
      'def build_dxf(path="imported_fss_pattern.dxf"):',
      "    doc = ezdxf.new('R2000')",
      "    doc.header['$INSUNITS'] = 4  # millimetres",
      "    doc.layers.new('METAL_OUTER', dxfattribs={'color': 4})",
      "    doc.layers.new('METAL_HOLE', dxfattribs={'color': 1})",
      "    doc.layers.new('CELL_GUIDE', dxfattribs={'color': 8})",
      '    model = doc.modelspace()',
      '    for loop in LOOPS_MM:',
      "        layer = 'METAL_HOLE' if loop['hole'] else 'METAL_OUTER'",
      "        model.add_lwpolyline(loop['points'], close=True, dxfattribs={'layer': layer})",
      ...(options.guide ? [
        '    x0, y0 = LEFT_MM, BOTTOM_MM',
        '    model.add_lwpolyline([(x0,y0),(x0+WIDTH_MM,y0),(x0+WIDTH_MM,y0+HEIGHT_MM),(x0,y0+HEIGHT_MM)],',
        "                          close=True, dxfattribs={'layer':'CELL_GUIDE'})"
      ]:[]),
      '    doc.saveas(path)',
      '    return path',
      '',
      "if __name__ == '__main__':",
      '    print("DXF generated:", build_dxf())',
      '',
      '# In CST, create metal faces from METAL_OUTER and subtract METAL_HOLE.',
      '# A closed DXF polyline is a contour, not automatically a conductive face.',
      ''
    ].join('\n');
  }
  return shared + [
    '# pip install numpy pypssfss',
    '# PyPSSFSS.pixels supports SQUARE unit cells; the original DXF code supports rectangles.',
    '# rasterization samples every pixel at its centre, so thin slits and diagonals are approximate.',
    '# IMPORTANT: clas="J" models METALLIC patch currents; M describes complementary apertures.',
    'import numpy as np',
    'GRID = ' + grid,
    'RUN_SOLVER = False  # Change to True after installing/initialising PyPSSFSS and Julia',
    '',
    'def make_pattern_matrix(resolution=GRID):',
    '    if abs(WIDTH_MM - HEIGHT_MM) > 1e-9 * max(1.0, WIDTH_MM, HEIGHT_MM):',
    '        raise ValueError("PyPSSFSS.pixels requires a square unit cell; use the DXF Python export for a rectangle.")',
    '    if not isinstance(resolution, int) or resolution < 2:',
    '        raise ValueError("resolution must be an integer >= 2")',
    '    # PSSFSS matrix row zero is the TOP row (maximum Y).',
    '    x_centres = LEFT_MM + (np.arange(resolution) + 0.5) * WIDTH_MM / resolution',
    '    y_centres = BOTTOM_MM + HEIGHT_MM - (np.arange(resolution) + 0.5) * HEIGHT_MM / resolution',
    '    mat = np.zeros((resolution, resolution), dtype=np.int32)',
    '    # Half-open crossing rule avoids double-counting vertices.  XOR provides',
    '    # even-odd filling for holes AND metal islands nested inside holes.',
    '    for loop in LOOPS_MM:',
    "        pts = loop['points']",
    '        for row, y in enumerate(y_centres):',
    '            cross_x = []',
    '            for i, (ax, ay) in enumerate(pts):',
    '                bx, by = pts[(i + 1) % len(pts)]',
    '                if (ay <= y < by) or (by <= y < ay):',
    '                    cross_x.append(ax + (y - ay) * (bx - ax) / (by - ay))',
    '            cross_x.sort()',
    '            if len(cross_x) % 2:',
    '                raise ValueError("Invalid / self-intersecting boundary")',
    '            for left, right in zip(cross_x[::2], cross_x[1::2]):',
    "                start = np.searchsorted(x_centres, left, side='left')",
    "                stop = np.searchsorted(x_centres, right, side='left')",
    '                mat[row, start:stop] ^= 1',
    '    return mat',
    '',
    'def build_sheet(pattern=None):',
    '    from pypssfss import pixels, mm',
    '    if pattern is None:',
    '        pattern = make_pattern_matrix()',
    '    return pixels(P=WIDTH_MM, patternmat=pattern, units=mm, clas="J", pdiv=1)',
    '',
    "if __name__ == '__main__':",
    '    pattern = make_pattern_matrix()',
    "    np.savetxt('imported_fss_pixels.csv', pattern, fmt='%d', delimiter=',')",
    '    print("Generated metal matrix:", pattern.shape, "metal pixels:", int(pattern.sum()))',
    '    if RUN_SOLVER:',
    '        from pypssfss import Layer, ThetaPhi, analyze, atoutputs, extract_result',
    '        sheet = build_sheet(pattern)',
    '        # Default example: PEC pattern suspended in AIR, without substrate.',
    '        # Replace strata, frequencies and angles with your actual model.',
    '        strata = [Layer(), sheet, Layer()]',
    '        freqs_ghz = np.linspace(8.0, 16.0, 81)',
    '        steering = ThetaPhi([0, 45], 0)',
    '        results = analyze(strata, freqs_ghz, steering, showprogress=True)',
    "        columns = atoutputs('FGHz theta s21dB(te,te) s21dB(tm,tm) s11dB(te,te) s11dB(tm,tm)')",
    '        print(extract_result(results, columns))',
    ''
  ].join('\n');
}
const api = {generatedPython};
if (typeof module !== 'undefined' && module.exports) module.exports = api;
else root.FSSCodegen = api;
})(typeof self !== 'undefined' ? self : globalThis);
